import sys, time; sys.path.insert(0, "..")
import numpy as np, score as S
for tag in ["fine", "skrog"]:
    V = np.load(f"V_{tag}.npy"); F = np.load(f"F_{tag}.npy"); lab = np.load(f"lab_{tag}.npy")
    fn, area, cen, asp, lmax = S.face_geom(V, F)
    vol = S.signed_volume(V, F)
    nc = lab.max() + 1
    cv = np.bincount(lab, weights=vol, minlength=nc)
    ext = lab == int(np.argmax(cv))
    t = time.time()
    slz = S.Slicer(V, F, 2, 10.0)
    wl, tr = S.waterline_fairness(slz, fn)
    t1 = time.time()
    print(tag, "waterlines %.1fs" % (t1 - t))
    for k, v in wl.items(): print("  ", k, v)
    slx = S.Slicer(V, F, 0, 10.0)
    rows = S.station_sweep(slx, np.arange(30.0, 7900.0, 10.0), fn)
    D = S.assemble_deck_line(rows)
    dl, _ = S.deckline_fairness(D)
    print("  deck line", dl)
    t = time.time()
    sf, _ = S.section_fairness(slx)
    print("  sections %.1fs" % (time.time() - t))
    for r in sf: print("    ", r)
    topo = S.edge_topology(F, len(V))
    skin = S.hull_skin_mask(cen, fn, ext)
    mq, ang = S.mesh_quality(topo, fn, asp, lmax, skin)
    print("  mesh", mq)
    deck = S.deck_mask(cen, fn, ext)
    t = time.time()
    wt, _ = S.wall_thickness(V, F, fn, area, cen, skin, deck, 30000)
    print("  thickness %.1fs" % (time.time() - t), wt)
